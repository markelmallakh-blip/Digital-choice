#!/usr/bin/env python3
"""Tiny static builder for the Digital Choice site.

    python3 build.py

Reads src/pages/*.html (each starts with a <!--meta {...} --> JSON line), wraps them
in the shared shell + partials and writes the finished pages to the project root.
Inside a page, `<!--include name-->` pulls in src/partials/name.html.
"""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
PARTIALS = SRC / "partials"

FONTS = ("https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,300..900"
         "&family=JetBrains+Mono:wght@400;500&family=Tajawal:wght@400;500;700;800&display=swap")

SCRIPTS = [
    "https://cdn.jsdelivr.net/npm/gsap@3.13.0/dist/gsap.min.js",
    "https://cdn.jsdelivr.net/npm/gsap@3.13.0/dist/ScrollTrigger.min.js",
    "https://cdn.jsdelivr.net/npm/gsap@3.13.0/dist/Flip.min.js",
    "https://cdn.jsdelivr.net/npm/lenis@1.3.4/dist/lenis.min.js",
    "js/data.js",
    "js/main.js",
]


def versioned(url: str) -> str:
    """Local asset → url?v=<content hash>, so browsers never run a stale copy."""
    local = ROOT / url
    if url.startswith("http") or not local.exists():
        return url
    return f"{url}?v={hashlib.md5(local.read_bytes()).hexdigest()[:8]}"


def partial(name: str) -> str:
    return (PARTIALS / f"{name}.html").read_text()


def includes(html: str) -> str:
    return re.sub(r"<!--include ([\w-]+)-->", lambda m: partial(m.group(1)).rstrip(), html)


def build_page(path: Path) -> str:
    raw = path.read_text()
    m = re.match(r"<!--meta (\{.*?\}) -->\n", raw, re.S)
    if not m:
        raise SystemExit(f"{path.name}: missing <!--meta {{...}} --> header")
    meta = json.loads(m.group(1))
    body = includes(raw[m.end():])
    nav = meta.get("nav", "")
    loader = meta.get("loader", False)

    chrome = partial("chrome")
    chrome = re.sub(r"\{\{active:(\w+)\}\}", lambda a: "is-active" if a.group(1) == nav else "", chrome)
    chrome = chrome.replace(' class="roll "', ' class="roll"').replace(' class=""', "")

    body_class = " ".join(c for c in [meta.get("bodyClass", ""), "is-loading" if loader else ""] if c)
    scripts = "\n".join(f'  <script src="{versioned(s)}"></script>' for s in SCRIPTS)

    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>{meta['title']}</title>
  <meta name="description" content="{meta['desc']}" />
  <meta name="theme-color" content="#FFFFFF" />
  <meta property="og:title" content="{meta['title']}" />
  <meta property="og:description" content="{meta['desc']}" />
  <link rel="icon" type="image/svg+xml" href="assets/img/favicon.svg" />
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="{FONTS}" rel="stylesheet" />
  <link rel="stylesheet" href="{versioned('css/style.css')}" />
  <link rel="stylesheet" href="{versioned('css/pages.css')}" />
</head>
<body class="{body_class}" data-page="{nav}">
<!-- Generated by build.py from src/pages/{path.name} — edit the source, not this file. -->

{partial('symbols').rstrip()}

{partial('loader').rstrip() if loader else ''}

{chrome.rstrip()}

  <div class="smooth" id="top">
  <main>
{body.rstrip()}
  </main>

{partial('footer').rstrip()}
  </div>

{scripts}
</body>
</html>
"""


def main() -> None:
    for page in sorted((SRC / "pages").glob("*.html")):
        out = ROOT / page.name
        out.write_text(build_page(page))
        print(f"built {out.name}")


if __name__ == "__main__":
    main()
